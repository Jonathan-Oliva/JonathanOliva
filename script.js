let currentLang = 'en';
let skipAnimation = false;
let currentRenderId = 0;

const container = document.getElementById('text-container');
const skipBtn = document.getElementById('skip-btn');
const langBtn = document.getElementById('lang-btn');

// Inyectamos textos iniciales
skipBtn.textContent = i18n[currentLang].skipBtn;
langBtn.textContent = i18n[currentLang].langBtn;

const triggerSkip = (e) => {
    if (e && e.target === langBtn) return; // Evitar que cliquear lenguaje lo skipee como efecto secundario
    if (!skipAnimation) {
        skipAnimation = true;
        skipBtn.style.display = 'none';
    }
};

skipBtn.addEventListener('click', triggerSkip);
document.addEventListener('keydown', triggerSkip);
document.addEventListener('click', triggerSkip);

langBtn.addEventListener('click', async (e) => {
    e.stopPropagation(); // Evitar que se propague el click y dispare skip

    // Cambiar el idioma
    currentLang = currentLang === 'en' ? 'es' : 'en';

    // Actualizar los botones
    langBtn.textContent = i18n[currentLang].langBtn;
    skipBtn.textContent = i18n[currentLang].skipBtn;

    // Reiniciamos la animación en el nuevo idioma
    skipAnimation = false;
    skipBtn.style.display = 'block';
    container.innerHTML = ""; // Limpiamos la pantalla previamente

    await init();
});

async function typeLine(renderId, text, speed = 15, isTitle = false, className = "line") {
    // Si cambió el contexto de renderizado durante espera asíncrona, cortamos el hilo antiguo.
    if (renderId !== currentRenderId) return;

    const line = document.createElement('div');
    line.className = className;
    if (isTitle) line.classList.add('section-title');
    container.appendChild(line);

    if (skipAnimation) {
        line.innerHTML = text; // Bypass completo
        return;
    }

    if (text.includes('<a') || text.includes('<span')) {
        line.innerHTML = text;
        await new Promise(r => setTimeout(r, speed * 2));
    } else {
        for (let char of text) {
            if (renderId !== currentRenderId) return; // Chequeo constante de cierre de hilo asíncrono
            line.textContent += char;
            if (!skipAnimation) {
                window.scrollTo(0, document.documentElement.scrollHeight);
                await new Promise(r => setTimeout(r, speed));
            }
        }
        if (renderId !== currentRenderId) return;
        if (skipAnimation) line.innerHTML = text;
    }
}

